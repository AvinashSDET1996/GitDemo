package variables;

public class sample1 
{
  public static void main(String[] args) 
  {
	   //1. Variable declaration(Allocating/reserving memory)
	      String sname;             //String= Datatype;    sname = reserving memory
	      int srollnum;
	      char sgrade;
	      float sper;
	      double height;
	      String sdept;
	      
	      //2. Variable Initialization(Assigning or Inserting value)
	        sname = "Avinash";
	        srollnum =100;
	        sgrade = 'A';
	        sper= 56.5f;
	        height = 86.78;
	        sdept = "Electronics";
	        
	     //3. Variable usage
	        System.out.println(sname);
	        System.out.println(srollnum);
	        System.out.println(sgrade);
	        System.out.println(sper);
	        System.out.println(height);
	        System.out.println(sdept);
	        System.out.println(sdept);            //Reusability
	        
	      
	      
	  
}
}
